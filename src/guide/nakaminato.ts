/** 当日の流れの 1 行分。時刻が決まっていない行は time を空にする */
export type GuideStop = {
  time: string
  title: string
  /** 補足。チラシに説明の無い行は省く */
  note?: string
  /** Google マップで開く場所（名前か「緯度,経度」）。移動しない行は省く */
  mapQuery?: string
}

/** 集合・休憩・編集・発表の会場 */
export type GuideVenue = {
  name: string
  address: string
  note: string
  mapQuery: string
}

export type EventGuide = {
  /** イベント名（見出し用） */
  title: string
  /** つなげるの表紙の既定の文字（App が JoinPanel に渡す）。表紙は 1 文字ずつ折り返すので、英単語が途中で割れないよう改行を入れておく */
  coverText: string
  date: string
  place: string
  /** チラシのキャッチコピー */
  catchphrase: string
  concept: string
  /** この企画で大切にすること */
  points: string[]
  stops: GuideStop[]
  venue: GuideVenue
  /** 参加前の準備（アプリについて） */
  prep: string
  organizer: string
}

